def sql_escape(value):
    return value.replace("'", "''")


def main():
    rows = []
    for category, label, lo, hi, commission, items in GROUPS:
        for code, name, provider in items:
            rows.append("('{}', '{}', '{}', '{}', '{}', {}, {}, {})".format(
                code, sql_escape(name), sql_escape(category), sql_escape(provider),
                sql_escape(label), lo, hi, commission))

    assert len(rows) == 100, "ожидалось 100 услуг, получилось %d" % len(rows)

    out = [
        "-- =====================================================================",
        "-- Каталог услуг для оплаты: 100 позиций.",
        "-- Файл сгенерирован скриптом tools/gen_catalog.py — правьте скрипт, не SQL.",
        "-- =====================================================================",
        "",
        "insert into service_catalog (code, name, category, provider, account_label, "
        "min_amount, max_amount, commission_percent)",
        "values",
    ]
    out.append(",\n".join("       " + r for r in rows) + ";")
    out.append("")

    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                          "bank-app", "src", "main", "resources", "db", "migration",
                          "V2__catalog.sql")
    with io.open(os.path.normpath(target), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("Записано услуг: %d -> %s" % (len(rows), os.path.normpath(target)))


if __name__ == "__main__":
    main()
